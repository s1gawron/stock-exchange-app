CREATE TABLE public__transaction
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wallet_id                 BIGINT                                  NOT NULL,
    transaction_type          VARCHAR(255)                            NOT NULL,
    transaction_status        VARCHAR(255)                            NOT NULL,
    transaction_create_date   TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    transaction_process_date  TIMESTAMP WITHOUT TIME ZONE,
    balance_blocked           NUMERIC(19, 4),
    balance_after_transaction NUMERIC(19, 4),
    stock_ticker              VARCHAR(255)                            NOT NULL,
    stock_price_limit         NUMERIC(19, 4)                          NOT NULL,
    stock_quantity            NUMERIC(19, 6)                          NOT NULL,
    stock_currency            VARCHAR(3)                              NOT NULL,
    CONSTRAINT pk_public__transaction PRIMARY KEY (id)
);

CREATE TABLE public__user
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    active    BOOLEAN                                 NOT NULL,
    username  VARCHAR(255)                            NOT NULL,
    email     VARCHAR(255)                            NOT NULL,
    password  VARCHAR(255)                            NOT NULL,
    user_role VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_public__user PRIMARY KEY (id)
);

CREATE TABLE public__user_stock_position
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wallet_id          BIGINT                                  NOT NULL,
    ticker             VARCHAR(255)                            NOT NULL,
    currency           VARCHAR(3)                              NOT NULL,
    quantity_available NUMERIC(19, 6)                          NOT NULL,
    quantity_blocked   NUMERIC(19, 6)                          NOT NULL,
    open_price         NUMERIC(19, 4)                          NOT NULL,
    open_date          TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_public__user_stock_position PRIMARY KEY (id)
);

CREATE TABLE public__user_wallet
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id              BIGINT                                  NOT NULL,
    currency             VARCHAR(3)                              NOT NULL,
    balance_available    NUMERIC(19, 4)                          NOT NULL,
    balance_blocked      NUMERIC(19, 4)                          NOT NULL,
    last_day_value       NUMERIC(19, 4)                          NOT NULL,
    last_day_update_date TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_public__user_wallet PRIMARY KEY (id)
);

